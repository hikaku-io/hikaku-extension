// End-to-end smoke test: loads the unpacked extension in Chrome for Testing,
// serves a local page with labelled images (from the eval cache), and checks the
// whole pipeline: service worker, metadata, offscreen ONNX model, content-script dots.
//
// Usage: npm run eval-model (once, to fill .eval-cache)  then  node scripts/e2e.mjs [screenshotDir]
import puppeteer from 'puppeteer';
import http from 'node:http';
import { readFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const EXT = process.env.EXT_DIR || ROOT; // test a build with EXT_DIR=dist/hikaku-x.y.z
const CACHE = join(ROOT, '.eval-cache');
const SHOTS = process.argv[2] || join(ROOT, '.e2e-shots');
mkdirSync(SHOTS, { recursive: true });
const sha = (s) => createHash('sha1').update(s).digest('hex');

// Grab labelled images from the eval cache.
const catUrl = (cat) => `https://commons.wikimedia.org/w/api.php?action=query&format=json&generator=categorymembers&gcmtitle=${encodeURIComponent('Category:' + cat)}&gcmtype=file&gcmlimit=40&prop=imageinfo&iiprop=url|mime&iiurlwidth=640`;
function pick(cat, n, label) {
  const f = join(CACHE, sha(catUrl(cat)));
  if (!existsSync(f)) throw new Error(`Run npm run eval-model first (missing cache for ${cat})`);
  return Object.values(JSON.parse(readFileSync(f)).query.pages)
    .map((p) => p.imageinfo?.[0]?.thumburl)
    .filter((u) => u && existsSync(join(CACHE, sha(u))))
    .slice(0, n)
    .map((u) => ({ label, file: join(CACHE, sha(u)) }));
}
const images = [
  ...pick('Images generated by Adobe Firefly AI', 2, 'ai'),
  ...pick('Images generated by Stable Diffusion', 2, 'ai'),
  ...pick('Featured pictures of landscapes', 2, 'real'),
  ...pick('Quality images of people', 2, 'real'),
];

// Synthetic C2PA-tagged JPEG (metadata path).
const box = (() => {
  const enc = (s) => Buffer.from(s, 'latin1');
  const u32 = (n) => { const b = Buffer.alloc(4); b.writeUInt32BE(n); return b; };
  const label = Buffer.concat([enc('c2pa'), Buffer.from([0])]);
  const jumd = Buffer.concat([u32(8 + 16 + 1 + label.length), enc('jumd'), enc('c2pa'), Buffer.alloc(12), Buffer.from([3]), label]);
  const payload = Buffer.concat([Buffer.from([0x6f]), enc('claim_generator'), Buffer.from([0x67]), enc('ChatGPT'), enc('http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia')]);
  const jumb = Buffer.concat([u32(8 + jumd.length + payload.length), enc('jumb'), jumd, payload]);
  const seg = Buffer.concat([enc('JP'), Buffer.from([0, 1]), u32(1), jumb]);
  const len = Buffer.alloc(2); len.writeUInt16BE(seg.length + 2);
  return Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xeb]), len, seg, Buffer.from([0xff, 0xd9])]);
})();

