// Sanity-check the visual model in Node (WASM backend) on labelled images from
// Wikimedia Commons. NOT a benchmark: small sample, Commons-specific content.
//
// Usage: npm run setup -- --model=uint8   (once)
//        npm run eval-model -- [--n=10] [--variant=uint8]
import * as ort from 'onnxruntime-web';
import jpeg from 'jpeg-js';
import { PNG } from 'pngjs';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { MODEL, localPath } from '../lib/model-config.js';
import { rgbaToCHW, aiProbability, resizeRGBA, looksLikeGraphic } from '../lib/preprocess.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(ROOT, '.eval-cache');
const arg = (k, d) => process.argv.find((a) => a.startsWith(`--${k}=`))?.split('=')[1] ?? d;
const N = Number(arg('n', 10));
const VARIANT = arg('variant', 'uint8');
const UA = 'Hikaku-eval/0.1 (research prototype; contact via project maintainer)';

const SETS = {
  ai: ['Images generated by DALL-E 3', 'Images generated by Stable Diffusion', 'Images generated by Adobe Firefly AI', 'Images generated by NightCafe Studio'],
  real: ['Quality images of people', 'Featured pictures of landscapes', 'Quality images of animals', 'Quality images of food'],
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
mkdirSync(CACHE, { recursive: true });

async function politeFetch(url, tries = 4) {
  for (let i = 0; i < tries; i++) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) return res;
    if (res.status === 429 || res.status >= 500) { await sleep(3000 * (i + 1)); continue; }
    throw new Error(`HTTP ${res.status} ${url}`);
  }
  throw new Error(`gave up: ${url}`);
}

async function cached(key, producer) {
  const f = join(CACHE, createHash('sha1').update(key).digest('hex'));
  if (existsSync(f)) return readFileSync(f);
  const buf = await producer();
  writeFileSync(f, buf);
  await sleep(1200);
  return buf;
}

async function listCategory(cat) {
  const url = `https://commons.wikimedia.org/w/api.php?action=query&format=json&generator=categorymembers&gcmtitle=${encodeURIComponent('Category:' + cat)}&gcmtype=file&gcmlimit=40&prop=imageinfo&iiprop=url|mime&iiurlwidth=640`;
  const json = JSON.parse(await cached(url, async () => Buffer.from(await (await politeFetch(url)).arrayBuffer())));
  return Object.values(json.query?.pages || {})
    .map((p) => ({ title: p.title, info: p.imageinfo?.[0] }))
    .filter((p) => p.info && /jpeg|png/.test(p.info.mime) && p.info.thumburl);
}

function decode(buf) {
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    const img = jpeg.decode(buf, { useTArray: true, formatAsRGBA: true, maxMemoryUsageInMB: 1024 });
    return { data: img.data, width: img.width, height: img.height };
  }
  const img = PNG.sync.read(buf);
  return { data: img.data, width: img.width, height: img.height };
}

// ------------------------------------------------------------ run

const modelFile = join(ROOT, localPath(VARIANT));
if (!existsSync(modelFile)) {
  console.error(`Missing ${localPath(VARIANT)} . Run: npm run setup -- --model=${VARIANT}`);
  process.exit(1);
}
ort.env.wasm.numThreads = 4;
let t0 = performance.now();
const session = await ort.InferenceSession.create(readFileSync(modelFile), { executionProviders: ['wasm'], graphOptimizationLevel: 'all' });
console.log(`Loaded ${VARIANT} model in ${Math.round(performance.now() - t0)} ms\n`);

const rows = [];
for (const [label, cats] of Object.entries(SETS)) {
  const perCat = Math.ceil(N / cats.length);
  for (const cat of cats) {
    let files;
    try { files = (await listCategory(cat)).slice(0, perCat); }
    catch (e) { console.warn(`! ${cat}: ${e.message}`); continue; }
    for (const f of files) {
      try {
        const buf = await cached(f.info.thumburl, async () => Buffer.from(await (await politeFetch(f.info.thumburl)).arrayBuffer()));
        const img = decode(buf);
        const rgba = resizeRGBA(img.data, img.width, img.height);
        if (looksLikeGraphic(rgba)) {
          // Extension skips the model here; counts as "not flagged".
          rows.push({ label, cat, title: f.title.replace(/^File:/, ''), p: 0, ms: 0, skipped: true });
          console.log(`${label === 'ai' ? 'AI  ' : 'REAL'}  skipped (screenshot/graphic)  ${f.title.replace(/^File:/, '').slice(0, 60)}`);
          continue;
        }
        const chw = rgbaToCHW(rgba);
        t0 = performance.now();
        const out = await session.run({ [MODEL.inputName]: new ort.Tensor('float32', chw, [1, 3, MODEL.size, MODEL.size]) });
        const ms = performance.now() - t0;
        const p = aiProbability(out[MODEL.outputName].data);
        rows.push({ label, cat, title: f.title.replace(/^File:/, ''), p, ms });
        console.log(`${label === 'ai' ? 'AI  ' : 'REAL'}  P(AI)=${p.toFixed(3)}  ${Math.round(ms)}ms  ${f.title.replace(/^File:/, '').slice(0, 60)}`);
      } catch (e) {
        console.warn(`! ${f.title}: ${e.message}`);
      }
    }
  }
}

// ------------------------------------------------------------ summary

const ai = rows.filter((r) => r.label === 'ai'), real = rows.filter((r) => r.label === 'real');
console.log(`\n${ai.length} AI images, ${real.length} real images · mean inference ${Math.round(rows.reduce((a, r) => a + r.ms, 0) / rows.length)} ms (Node WASM, ${VARIANT})`);
console.log('threshold  AI caught (TPR)  real wrongly flagged (FPR)');
for (const t of [0.5, 0.7, 0.9]) {
  const tpr = ai.filter((r) => r.p >= t).length / (ai.length || 1);
  const fpr = real.filter((r) => r.p >= t).length / (real.length || 1);
  console.log(`  ${t.toFixed(2)}      ${(tpr * 100).toFixed(0).padStart(3)}%              ${(fpr * 100).toFixed(0).padStart(3)}%`);
}
